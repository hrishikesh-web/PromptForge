#!/usr/bin/env node
/**
 * Generates the SQL migrations for the PromptForge demo library from library.js.
 *
 *   node database/library/build.js          (from the promptforge folder)
 *
 * Output (overwritten each time, never executed by this script):
 *   database/migrations/002_taxonomy.sql
 *   database/migrations/003_demo_accounts.sql
 *   database/migrations/004_promote_admin.sql
 *   database/migrations/005_prompt_library.sql
 *   database/migrations/006_demo_activity.sql
 *   database/sample_queries.sql            (the six use cases, from server/sql/useCases.js)
 *
 * Design rules for the generated SQL:
 *  - Rows are found by NAME/EMAIL/TITLE, never by numeric id, so the same file works
 *    on the existing database and on a fresh install.
 *  - Re-running is safe: INSERT IGNORE on UNIQUE keys or WHERE NOT EXISTS guards.
 *  - Nothing is deleted, truncated or dropped. Existing rows are never overwritten,
 *    except category descriptions and three same-meaning renames (documented in 002).
 *  - Statements that refer to Hrishikesh's account simply insert nothing if that
 *    account has not been registered yet (the JOIN finds no row).
 */
const fs = require('fs');
const path = require('path');
const L = require('./library');
const UC = require('../../server/sql/useCases');

const OUT = path.join(__dirname, '..', 'migrations');
// bcrypt hash of a random 64-character secret that was thrown away: nobody can log in
// with it. `npm run demo:passwords` replaces it for demo accounts only.
const LOCKED_HASH = '$2a$10$wDLjy6W4rwQTsG2r8v0YEubyreICvNTx4a1X6gjb1NyqT2m273l5O';

/* ------------------------------------------------------------------ helpers */

const assertAscii = (label, s) => {
  if (/[^\x09\x0a\x0d\x20-\x7e]/.test(s)) throw new Error(`${label} contains non-ASCII characters: ${JSON.stringify(s.match(/[^\x09\x0a\x0d\x20-\x7e]/)[0])}`);
  if (s.includes('\\')) throw new Error(`${label} contains a backslash (not allowed, avoids SQL escape-mode differences)`);
};
/** SQL string literal. Backslashes are rejected above, so doubling quotes is sufficient. */
const q = (s) => {
  const str = String(s);
  assertAscii('value', str);
  return `'${str.replace(/'/g, "''")}'`;
};
const ago = (days, hours = 0) => `NOW() - INTERVAL ${days} DAY${hours ? ` + INTERVAL ${hours} HOUR` : ''}`;
const header = (title, lines) =>
  `-- =============================================================================\n-- ${title}\n-- -----------------------------------------------------------------------------\n${lines
    .map((l) => `-- ${l}`.trimEnd())
    .join('\n')}\n-- GENERATED by database/library/build.js from library.js. Edit library.js, not this file.\n-- =============================================================================\n\nUSE \`promptforge_db\`;\nSET NAMES utf8mb4;\n`;

// Deterministic pseudo-random numbers so the generated SQL is identical on every build.
let seed = 20261017;
const rand = () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const between = (a, b) => a + Math.floor(rand() * (b - a + 1));

const person = (k) => {
  const p = L.PEOPLE[k];
  if (!p) throw new Error(`Unknown person key ${k}`);
  return p;
};
const promptByKey = Object.fromEntries(L.PROMPTS.map((p) => [p.key, p]));

/** SQL fragment that finds one library prompt row as alias p (with author alias a). */
const findPrompt = (pr) => `prompts p INNER JOIN users a ON a.user_id = p.user_id AND a.email = ${q(person(pr.author).email)}`;
const wherePrompt = (pr) => `p.title = ${q(pr.title)}`;

/** Build version contents from the @v2/@v3 markers. */
const versionsOf = (pr) => {
  const lines = pr.content.split('\n');
  const upTo = (n) =>
    lines
      .filter((l) => {
        const m = l.match(/^@v(\d) /);
        return !m || Number(m[1]) <= n;
      })
      .map((l) => l.replace(/^@v\d /, ''))
      .join('\n');
  const max = Math.max(1, ...lines.map((l) => Number((l.match(/^@v(\d) /) || [])[1] || 1)));
  const out = [];
  for (let n = 1; n <= max; n++) {
    const notes = n === 1 ? 'Initial version' : pr[`v${n}Notes`] || `Updated to v${n}`;
    const after = n === 1 ? 0 : Math.min(pr[`v${n}After`] || (n === 2 ? Math.max(1, Math.round(pr.daysAgo * 0.25)) : Math.max(2, Math.round(pr.daysAgo * 0.6))), pr.daysAgo - 1);
    out.push({ n, content: upTo(n), notes, after });
  }
  return out;
};

/* ------------------------------------------------------------------ validation */

const validate = () => {
  const titles = new Set();
  const tagNames = new Set();
  for (const pr of L.PROMPTS) {
    ['title', 'description', 'content'].forEach((f) => assertAscii(`${pr.key}.${f}`, pr[f]));
    if (titles.has(pr.title)) throw new Error(`Duplicate title: ${pr.title}`);
    titles.add(pr.title);
    if (pr.title.length > 255) throw new Error(`${pr.key}: title too long`);
    if (pr.description.length > 1000) throw new Error(`${pr.key}: description too long`);
    if (!L.CATEGORIES.some((c) => c.name === pr.category)) throw new Error(`${pr.key}: unknown category ${pr.category}`);
    if (!L.MODELS.some((m) => m.name === pr.model)) throw new Error(`${pr.key}: unknown model ${pr.model}`);
    if (pr.tags.length < 1 || pr.tags.length > 5) throw new Error(`${pr.key}: needs 1-5 tags`);
    pr.tags.forEach((t) => {
      if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(t) || t.length < 2 || t.length > 40) throw new Error(`${pr.key}: bad tag ${t}`);
      tagNames.add(t);
    });
    if (!/\{\{[a-z][a-z0-9_]*\}\}/.test(pr.content)) throw new Error(`${pr.key}: has no {{placeholder}}`);
    person(pr.author);
  }
  for (const c of L.COMMENTS) {
    if (!promptByKey[c.prompt]) throw new Error(`comment on unknown prompt ${c.prompt}`);
    if (promptByKey[c.prompt].author === c.by) throw new Error(`self-comment on ${c.prompt}`);
    if (c.daysAfter >= promptByKey[c.prompt].daysAgo) throw new Error(`comment on ${c.prompt} would be in the future`);
    assertAscii(`comment ${c.prompt}`, c.text);
  }
  for (const [a, b] of L.FOLLOWS) if (a === b) throw new Error('self-follow');
  return [...tagNames].sort();
};

/* ------------------------------------------------------------------ 002 taxonomy */

const buildTaxonomy = (tags) => {
  let s = header('Migration 002 - categories, suggested models and tags for the new library', [
    'Re-run: SAFE (idempotent).',
    'Changes to EXISTING rows (all reversible, no data removed):',
    "  * Category renames (only if the new name does not exist yet):",
    ...L.CATEGORIES.filter((c) => c.renamedFrom).map((c) => `      "${c.renamedFrom}"  ->  "${c.name}"`),
    '    Prompts already in those categories stay in them under the new name.',
    '  * Category descriptions are set for the 10 library categories.',
    '  * Tag renames with the same meaning (only if the new name does not exist yet):',
    ...L.TAG_RENAMES.map(([a, b]) => `      #${a}  ->  #${b}`),
    'Everything else is INSERT IGNORE (new rows only). Old categories, models and tags',
    'that the library does not use are left alone; see 099_legacy_cleanup_DRAFT.sql.',
    'Rollback: rename back with UPDATE ... SET name = old WHERE name = new (see bottom).'
  ]);

  s += '\n-- PRE-CHECK: current categories, models and tags\nSELECT category_id, name FROM categories ORDER BY category_id;\nSELECT model_id, model_name, provider FROM ai_models ORDER BY model_id;\nSELECT tag_id, tag_name FROM tags ORDER BY tag_id;\n';

  s += '\n-- 1) Category renames. The check is stored in a variable first, because MySQL does not\n--    allow an UPDATE to read the same table in a subquery (error 1093).\n';
  for (const c of L.CATEGORIES.filter((x) => x.renamedFrom)) {
    s += `SET @target_exists = (SELECT COUNT(*) FROM categories WHERE name = ${q(c.name)});\nUPDATE categories SET name = ${q(c.name)} WHERE name = ${q(c.renamedFrom)} AND @target_exists = 0;\n`;
  }

  s += '\n-- 2) The 10 library categories (new ones inserted, descriptions refreshed)\n';
  s += `INSERT INTO categories (name, description) VALUES\n${L.CATEGORIES.map((c) => `  (${q(c.name)}, ${q(c.description)})`).join(',\n')}\nON DUPLICATE KEY UPDATE description = VALUES(description);\n`;

  s += '\n-- 3) Model-agnostic "suggested model" rows (context_window 0 = not applicable)\n';
  s += `INSERT IGNORE INTO ai_models (model_name, provider, context_window) VALUES\n${L.MODELS.map((m) => `  (${q(m.name)}, ${q(m.provider)}, 0)`).join(',\n')};\n`;

  s += '\n-- 4) Same-meaning tag renames (keeps existing prompt links)\n';
  for (const [from, to] of L.TAG_RENAMES) {
    s += `SET @target_exists = (SELECT COUNT(*) FROM tags WHERE tag_name = ${q(to)});\nUPDATE tags SET tag_name = ${q(to)} WHERE tag_name = ${q(from)} AND @target_exists = 0;\n`;
  }

  s += `\n-- 5) Library tags (${tags.length})\nINSERT IGNORE INTO tags (tag_name) VALUES\n${tags.map((t) => `  (${q(t)})`).join(',\n')};\n`;

  s += '\n-- VERIFY\nSELECT c.name, COUNT(p.prompt_id) AS prompts FROM categories c LEFT JOIN prompts p ON p.category_id = c.category_id GROUP BY c.category_id, c.name ORDER BY c.name;\n';
  s += `SELECT COUNT(*) AS library_tags_present FROM tags WHERE tag_name IN (${tags.map(q).join(', ')});\n`;

  s += '\n-- ROLLBACK (only if you need to undo the renames):\n';
  for (const c of L.CATEGORIES.filter((x) => x.renamedFrom)) s += `-- UPDATE categories SET name = ${q(c.renamedFrom)} WHERE name = ${q(c.name)};\n`;
  for (const [from, to] of L.TAG_RENAMES) s += `-- UPDATE tags SET tag_name = ${q(from)} WHERE tag_name = ${q(to)};\n`;
  return s;
};

