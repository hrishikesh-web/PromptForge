if (CHECK) {
  // Used by `npm test`: fail if library.js changed but the SQL files were not regenerated.
  const stale = outputs.filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== c);
  if (stale.length) {
    console.error(`Library SQL is out of date: ${stale.map(([f]) => rel(f)).join(', ')}. Run: npm run db:build-library`);
    process.exit(1);
  }
  console.log(`Library OK: ${L.PROMPTS.length} prompts, ${tags.length} tags, generated SQL is up to date.`);
} else {
  console.log('Building PromptForge library SQL...');
  outputs.forEach(([f, c]) => {
    fs.writeFileSync(f, c);
    console.log(`  wrote ${rel(f)}`);
  });
  console.log(
    `Done: ${L.PROMPTS.length} prompts, ${tags.length} tags, ${L.CATEGORIES.length} categories, ` +
      `${activity.counts.likes} likes, ${activity.counts.bookmarks} bookmarks, ${activity.counts.ratings} ratings, ${L.COMMENTS.length} comments.`
  );
}
