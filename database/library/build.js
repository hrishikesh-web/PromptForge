/* ------------------------------------------------------------------ 005 prompt library */

const buildLibrary = () => {
  let s = header(`Migration 005 - the prompt library (${L.PROMPTS.length} prompts with versions and tags)`, [
    'Requires 002 and 003 first. Prompts by Hrishikesh are only added if his account exists (004).',
    'Each prompt is inserted only if the same author does not already have a prompt with that title.',
    'Versions use INSERT IGNORE on UNIQUE(prompt_id, version_number): an existing version is never',
    'overwritten, so edits you make later in the app are safe if you re-run this file.',
    'Dates are relative to NOW() so the analytics windows (last 30 days, last 6 months) have data.',
    'Re-run: SAFE. Rollback: delete these prompts by title (CASCADE removes versions, tags and activity).'
  ]);

  for (const pr of L.PROMPTS) {
    const versions = versionsOf(pr);
    const latest = versions[versions.length - 1];
    const hour = between(8, 21);
    s += `\n-- ${pr.title}  [${person(pr.author).name}, ${pr.category}, ${versions.length} version(s)]\n`;
    s += `INSERT INTO prompts (user_id, category_id, model_id, title, description, status, is_moderated, created_at, updated_at)
SELECT u.user_id, c.category_id, m.model_id, ${q(pr.title)}, ${q(pr.description)}, ${q(pr.status || 'published')}, FALSE,
       ${ago(pr.daysAgo, hour)}, ${ago(pr.daysAgo - latest.after, hour)}
FROM users u
INNER JOIN categories c ON c.name = ${q(pr.category)}
INNER JOIN ai_models m ON m.model_name = ${q(pr.model)}
WHERE u.email = ${q(person(pr.author).email)}
  AND NOT EXISTS (SELECT 1 FROM prompts px WHERE px.user_id = u.user_id AND px.title = ${q(pr.title)});\n`;
    for (const v of versions) {
      s += `INSERT IGNORE INTO prompt_versions (prompt_id, version_number, content, change_notes, created_by, created_at)
SELECT p.prompt_id, ${v.n}, ${q(v.content)}, ${q(v.notes)}, p.user_id, p.created_at + INTERVAL ${v.after} DAY
FROM ${findPrompt(pr)} WHERE ${wherePrompt(pr)};\n`;
    }
    s += `INSERT IGNORE INTO prompt_tags (prompt_id, tag_id)
SELECT p.prompt_id, t.tag_id FROM ${findPrompt(pr)} INNER JOIN tags t ON t.tag_name IN (${pr.tags.map(q).join(', ')})
WHERE ${wherePrompt(pr)};\n`;
  }

  s += `\n-- VERIFY: prompts per author from this library\nSELECT u.name, COUNT(*) AS prompts, SUM(p.status = 'draft') AS drafts,\n       (SELECT COUNT(*) FROM prompt_versions v INNER JOIN prompts p2 ON p2.prompt_id = v.prompt_id WHERE p2.user_id = u.user_id) AS versions\nFROM prompts p INNER JOIN users u ON u.user_id = p.user_id\nWHERE p.title IN (${L.PROMPTS.map((p) => q(p.title)).join(',\n  ')})\nGROUP BY u.user_id, u.name ORDER BY u.name;\n`;
  return s;
};

/* ------------------------------------------------------------------ 006 demo activity */

const buildActivity = () => {
  let s = header('Migration 006 - SEEDED DEMONSTRATION ACTIVITY (likes, bookmarks, ratings, comments, follows)', [
    'This is demo data so every DBMS feature can be shown. It is NOT genuine user endorsement.',
    'Every activity_logs row written here carries "seeded_demo": true in its metadata.',
    'Requires 005. Rows involving Hrishikesh are skipped if his account does not exist.',
    'Matches application rules: nobody likes, rates or comments on their own prompt; drafts get none.',
    'Notifications use the same wording the application writes.',
    'Re-run: SAFE (UNIQUE keys + NOT EXISTS guards).',
    'Rollback: see 099_legacy_cleanup_DRAFT.sql notes, or delete rows WHERE metadata has seeded_demo.'
  ]);

  const keys = Object.keys(L.PEOPLE);
  const publicPrompts = L.PROMPTS.filter((p) => (p.status || 'published') === 'published');
  // Popularity weight: older, broadly useful prompts collect more activity.
  const pop = (pr) => Math.min(1, 0.25 + pr.daysAgo / 180 + (['open-book-notes', 'viva-prep', 'react-debug', 'question-bank', 'sql-generator', 'consistent-photo-look'].includes(pr.key) ? 0.3 : 0));
  const act = (pr) => {
    const d = between(1, Math.max(1, pr.daysAgo - 1));
    return { day: d, hour: between(0, 20) };
  };
  const at = (pr, t) => `LEAST(p.created_at + INTERVAL ${t.day} DAY + INTERVAL ${t.hour} HOUR, NOW())`;
  const log = (actorEmail, action, table, recordSql, demoKey, whenSql, fromSql) =>
    `INSERT INTO activity_logs (user_id, action, table_name, record_id, metadata, created_at)
SELECT actor.user_id, '${action}', '${table}', ${recordSql}, JSON_OBJECT('seeded_demo', TRUE, 'demo_key', ${q(demoKey)}), ${whenSql}
FROM ${fromSql}
  AND NOT EXISTS (SELECT 1 FROM activity_logs l WHERE l.action = '${action}' AND JSON_UNQUOTE(JSON_EXTRACT(l.metadata, '$.demo_key')) = ${q(demoKey)});\n`;
  const notify = (type, message, whenSql, fromSql, readAfterDays) =>
    `INSERT INTO notifications (user_id, sender_id, type, message, entity_type, entity_id, is_read, created_at)
SELECT p.user_id, actor.user_id, '${type}', ${message}, 'prompt', p.prompt_id, ${readAfterDays}, ${whenSql}
FROM ${fromSql}
  AND NOT EXISTS (SELECT 1 FROM notifications n WHERE n.user_id = p.user_id AND n.sender_id = actor.user_id
                  AND n.type = '${type}' AND n.entity_type = 'prompt' AND n.entity_id = p.prompt_id);\n`;

  const counts = { likes: 0, bookmarks: 0, ratings: 0 };
  for (const pr of publicPrompts) {
    const others = keys.filter((k) => k !== pr.author);
    const w = pop(pr);
    s += `\n-- ===== ${pr.title}\n`;
    let rated = false;
    others.forEach((k, idx) => {
      const actor = person(k);
      const from = `${findPrompt(pr)} INNER JOIN users actor ON actor.email = ${q(actor.email)}\nWHERE ${wherePrompt(pr)}`;
      const recent = (t) => (pr.daysAgo - t.day > 7 ? 1 : 0); // notifications older than a week are read

      if (rand() < 0.3 + 0.55 * w) {
        const t = act(pr);
        counts.likes++;
        s += `INSERT IGNORE INTO likes (prompt_id, user_id, created_at) SELECT p.prompt_id, actor.user_id, ${at(pr, t)} FROM ${from};\n`;
        s += notify('like', `CONCAT(actor.name, ' liked your prompt "', p.title, '".')`, at(pr, t), from, recent(t));
        s += log(actor.email, 'LIKE', 'likes', 'p.prompt_id', `like:${pr.key}:${k}`, at(pr, t), from);
      }
      if (rand() < 0.2 + 0.5 * w) {
        const t = act(pr);
        counts.bookmarks++;
        s += `INSERT IGNORE INTO bookmarks (prompt_id, user_id, created_at) SELECT p.prompt_id, actor.user_id, ${at(pr, t)} FROM ${from};\n`;
        s += log(actor.email, 'BOOKMARK', 'bookmarks', 'p.prompt_id', `bookmark:${pr.key}:${k}`, at(pr, t), from);
      }
      const mustRate = !rated && idx === others.length - 1;
      if (mustRate || rand() < 0.3 + 0.45 * w) {
        rated = true;
        const t = act(pr);
        const r = rand();
        const value = r < 0.45 + 0.3 * w ? 5 : r < 0.9 ? 4 : 3;
        counts.ratings++;
        s += `INSERT IGNORE INTO ratings (prompt_id, user_id, rating_value, created_at, updated_at) SELECT p.prompt_id, actor.user_id, ${value}, ${at(pr, t)}, ${at(pr, t)} FROM ${from};\n`;
        s += notify('rating', `CONCAT(actor.name, ' rated your prompt "', p.title, '" ${value} stars.')`, at(pr, t), from, recent(t));
        s += log(actor.email, 'RATE', 'ratings', 'p.prompt_id', `rate:${pr.key}:${k}`, at(pr, t), from);
      }
    });
  }

  s += '\n-- ===== Comments (hand-written, consistent with each prompt)\n';
  for (const c of L.COMMENTS) {
    const pr = promptByKey[c.prompt];
    const actor = person(c.by);
    const t = { day: c.daysAfter, hour: between(9, 22) };
    const from = `${findPrompt(pr)} INNER JOIN users actor ON actor.email = ${q(actor.email)}\nWHERE ${wherePrompt(pr)}`;
    s += `INSERT INTO comments (prompt_id, user_id, comment_text, created_at, updated_at)
SELECT p.prompt_id, actor.user_id, ${q(c.text)}, ${at(pr, t)}, ${at(pr, t)} FROM ${from}
  AND NOT EXISTS (SELECT 1 FROM comments cx WHERE cx.prompt_id = p.prompt_id AND cx.user_id = actor.user_id AND cx.comment_text = ${q(c.text)});\n`;
    s += notify('comment', `CONCAT(actor.name, ' commented on "', p.title, '".')`, at(pr, t), from, pr.daysAgo - t.day > 7 ? 1 : 0);
    s += log(
      actor.email,
      'COMMENT',
      'comments',
      `(SELECT MIN(cx.comment_id) FROM comments cx WHERE cx.prompt_id = p.prompt_id AND cx.user_id = actor.user_id AND cx.comment_text = ${q(c.text)})`,
      `comment:${c.prompt}:${c.by}:${c.daysAfter}`,
      at(pr, t),
      from
    );
  }

  s += '\n-- ===== Follows\n';
  L.FOLLOWS.forEach(([fromKey, toKey], i) => {
    const f = person(fromKey);
    const to = person(toKey);
    const days = 150 - i * 8;
    s += `INSERT IGNORE INTO follows (follower_id, following_id, created_at)
SELECT f.user_id, t.user_id, ${ago(days)} FROM users f INNER JOIN users t ON t.email = ${q(to.email)} WHERE f.email = ${q(f.email)};
INSERT INTO notifications (user_id, sender_id, type, message, entity_type, entity_id, is_read, created_at)
SELECT t.user_id, f.user_id, 'follow', CONCAT(f.name, ' started following you.'), 'user', f.user_id, ${days > 7 ? 1 : 0}, ${ago(days)}
FROM users f INNER JOIN users t ON t.email = ${q(to.email)} WHERE f.email = ${q(f.email)}
  AND NOT EXISTS (SELECT 1 FROM notifications n WHERE n.user_id = t.user_id AND n.sender_id = f.user_id AND n.type = 'follow');\n`;
  });

  s += '\n-- ===== Creation and edit history in activity_logs (what the app would have logged)\n';
  for (const pr of L.PROMPTS) {
    const from = `${findPrompt(pr)} INNER JOIN users actor ON actor.user_id = p.user_id\nWHERE ${wherePrompt(pr)}`;
    s += log('', 'CREATE_PROMPT', 'prompts', 'p.prompt_id', `create:${pr.key}`, 'p.created_at', from);
    for (const v of versionsOf(pr).slice(1)) {
      s += log('', 'UPDATE_PROMPT', 'prompts', 'p.prompt_id', `update:${pr.key}:v${v.n}`, `p.created_at + INTERVAL ${v.after} DAY`, from);
    }
  }

  s += `\n-- VERIFY (expected when all six accounts exist: about ${counts.likes} likes, ${counts.bookmarks} bookmarks, ${counts.ratings} ratings, ${L.COMMENTS.length} comments, ${L.FOLLOWS.length} follows)
SELECT
  (SELECT COUNT(*) FROM likes) AS likes,
  (SELECT COUNT(*) FROM bookmarks) AS bookmarks,
  (SELECT COUNT(*) FROM ratings) AS ratings,
  (SELECT COUNT(*) FROM comments) AS comments,
  (SELECT COUNT(*) FROM follows) AS follows,
  (SELECT COUNT(*) FROM notifications) AS notifications,
  (SELECT COUNT(*) FROM activity_logs WHERE JSON_EXTRACT(metadata, '$.seeded_demo') = TRUE) AS seeded_demo_log_rows;
`;
  return { sql: s, counts };
};

/* ------------------------------------------------------------------ sample_queries.sql */

const buildSampleQueries = () => {
  const inline = (sql, params) => {
    let i = 0;
    return sql.replace(/\?/g, () => {
      const v = params[i++];
      return typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
    });
  };
  const cases = [
    ['1', UC.topPromptsByEngagement()],
    ['2', UC.mostActiveCreators()],
    ['3', UC.filterByModelCategoryTag(UC.USE_CASE_3_EXAMPLE)],
    ['4', UC.usersWithMostBookmarks()],
    ['5', UC.avgRatingByCategory()],
    ['6', UC.monthlyCreationTrend({ months: 6 })]
  ];
  let s = `-- =============================================================================
-- PromptForge - the six DBMS SQL use cases (presentation slide 12)
-- -----------------------------------------------------------------------------
-- GENERATED from server/sql/useCases.js by database/library/build.js.
-- The website's Analytics page runs exactly these queries (with ? parameters);
-- here the example parameter values are written in so you can paste them into
-- MySQL Workbench. All queries are read-only SELECTs.
-- =============================================================================

USE \`promptforge_db\`;
`;
  for (const [n, c] of cases) {
    s += `\n-- -----------------------------------------------------------------------------\n-- USE CASE ${n}: ${c.title}\n-- Concepts: ${c.concepts.join(', ')}\n`;
    s += c.explanation.match(/.{1,90}(\s|$)/g).map((l) => `-- ${l.trim()}`).join('\n') + '\n';
    if (n === '3') s += `-- Example filters: category = '${UC.USE_CASE_3_EXAMPLE.category}', model = '${UC.USE_CASE_3_EXAMPLE.model}', tag = '${UC.USE_CASE_3_EXAMPLE.tag}'\n`;
    if (n === '2') s += "-- For a calendar month use: WHERE a.created_at >= '2026-10-01' AND a.created_at < DATE_ADD('2026-10-01', INTERVAL 1 MONTH)\n";
    s += `-- -----------------------------------------------------------------------------\n${inline(c.sql, c.params)};\n`;
  }
  return s;
};

